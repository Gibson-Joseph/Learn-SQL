 We have two types of CTE:
 
 1. Non-Recursive CTE
 - in non-recursive CTE we have two subtypes.
 -- 1. Stantalone CTE
 -- 2. Nested CTE
 
 2. Recursive CTE 
 
 Non-Recursive CTE: It means it is a CTE that executed only once. So there is not repetitions or lopping or anything so that SQL can excecuted in one go and that's it.
 
 Recursive CTE: This is exactly the opposite of Non-Recursive CTE. It is a self-referencing query that repeatedly processing the the data until a certain condition is met.
